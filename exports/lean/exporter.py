def verify_project(project_dir: Path) -> dict:
    """Verify the metadata stored under ``project_dir``.

    Returns a dict with keys:

    * ``ok`` (bool) -- True iff every check passed.
    * ``errors`` (list[str]) -- human-readable failure messages.
    * ``metadata`` (dict | None) -- the loaded ``qf_metadata.json``.

    Checks:

    * ``qf_metadata.json`` exists and is valid JSON.
    * The metadata declares ``policy_hash`` and ``spec_hash`` (both
      non-empty).
    * The metadata's ``policy_hash`` matches
      ``ProtocolPolicy.load()._with_hash().policy_hash`` (i.e. the
      currently active policy still matches the export).
    * The README ("DO NOT TRUST IN ISOLATION" warning) is present.

    The function never raises on a bad project; all failures are
    reported via the ``errors`` list so a CLI caller can render them.
    """
    project_dir = Path(project_dir)
    errors: list[str] = []
    metadata: Optional[dict] = None
    meta_path = project_dir / "qf_metadata.json"

    if not project_dir.exists():
        return {"ok": False, "errors": [f"project dir not found: {project_dir}"], "metadata": None}
    if not meta_path.exists():
        errors.append("qf_metadata.json missing")
        return {"ok": False, "errors": errors, "metadata": None}

    try:
        metadata = json.loads(meta_path.read_text(encoding="utf-8"))
    except Exception as e:
        errors.append(f"qf_metadata.json invalid JSON: {e}")
        return {"ok": False, "errors": errors, "metadata": None}

    for k in ("policy_hash", "spec_hash", "qf_version", "exported_at"):
        if not metadata.get(k):
            errors.append(f"qf_metadata.json missing required field {k!r}")

    declared_policy = str(metadata.get("policy_hash", ""))
    if declared_policy:
        active = ProtocolPolicy.load()
        active_hash = active._with_hash().policy_hash
        if declared_policy != active_hash:
            errors.append(
                "policy_hash mismatch: "
                f"export declares {declared_policy[:16]}..., "
                f"active policy is {active_hash[:16]}..."
            )

    readme_path = project_dir / "README.md"
    if readme_path.exists():
        try:
            readme = readme_path.read_text(encoding="utf-8")
            if "DO NOT TRUST IN ISOLATION" not in readme:
                errors.append("README.md missing 'DO NOT TRUST IN ISOLATION' warning")
        except Exception as e:
            errors.append(f"README.md unreadable: {e}")
    else:
        errors.append("README.md missing")

    return {"ok": not errors, "errors": errors, "metadata": metadata}


