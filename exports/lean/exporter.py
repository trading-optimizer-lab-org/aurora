"""Lean export adapter -- Aurora StrategySpec -> Lean C# project.

Both spec variants are accepted on input:

* :class:`aurora.research.factory.spec.StrategySpec` (immutable
  factory record with ``spec_hash``, ``policy_hash``, ``universe``,
  ``rebalance``, ``strategy_class``, ``params``).
* :class:`aurora.strategies.base.StrategySpec` (GA parameter-range
  descriptor with ``name``, ``params``).

Inputs are duck-typed: anything with at least ``name`` and ``params`` is
accepted. Optional attributes used when present:

* ``strategy_class`` -- fully qualified import path (factory variant).
* ``universe`` -- list of tickers (factory variant).
* ``rebalance`` -- cadence label (factory variant).
* ``spec_hash`` -- canonical hash (factory variant). When absent, the
  exporter computes a SHA-256 over the params payload.

Translation tiers (:meth:`LeanExporter._classify_translation`):

* ``"full"`` -- known QF strategy with a complete Lean equivalent
  template (``MACross``, ``RSIMeanRev`` minimal subset).
* ``"partial"`` -- known shape (e.g. ``TSMomentum``, ``BollingerMR``)
  with a Lean skeleton + TODO blocks for the bits that need a manual
  port.
* ``"scaffold-only"`` -- unknown class. The Lean ``OnData`` body is a
  TODO and the original params dict is embedded as a comment.

R54 note: every "TODO" / "FIXME" string in this module is content
embedded into the *generated Lean C# code*, not pending Python work.
The comments tell the Lean-side operator which methods need a manual
port; no Python action is required from Aurora maintainers.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from string import Template
from typing import Any, Optional

import pandas as pd

from aurora.core.protocol_policy import ProtocolPolicy


