@dataclass
class LeanExportConfig:
    """Configuration for a Lean export run.

    Attributes:
        target_directory: Parent directory under which a project
            sub-directory ``<project_name>/`` will be created.
        project_name: Name of the project directory and the C# class
            (sanitized to a valid C# identifier).
        cash: Initial cash for the Lean ``SetCash`` call.
        benchmark: Lean benchmark symbol (default ``"SPY"``).
        resolution: Lean ``Resolution`` enum value -- ``"Daily"`` /
            ``"Hour"`` / ``"Minute"`` / ``"Tick"``.
        universe_resolution: Lean ``UniverseSettings.Resolution`` value;
            usually equal to ``resolution``.
        start_date: Lean ``SetStartDate`` date.
        end_date: Optional ``SetEndDate``; ``None`` means an open-ended
            backtest (Lean defaults to "today").
        include_costs_from_policy: When ``True`` (default), the README
            mentions the QF cost-floor pulled from
            :class:`ProtocolPolicy`. Lean's own cost model is used at
            runtime; this flag only controls README annotation.
        include_validation_marker: When ``True``, the README and
            metadata reference any ``validation_marker`` passed to
            :meth:`LeanExporter.export`. When no marker is supplied, the
            README warns that the export is research-grade only.
    """

    target_directory: Path
    project_name: str
    start_date: pd.Timestamp
    cash: float = 100_000
    benchmark: str = "SPY"
    resolution: str = "Daily"
    universe_resolution: str = "Daily"
    end_date: Optional[pd.Timestamp] = None
    include_costs_from_policy: bool = True
    include_validation_marker: bool = True


@dataclass(frozen=True)
class LeanProjectArtifact:
    """Immutable result record from :meth:`LeanExporter.export`.

    Attributes:
        project_name: Name of the project directory (matches
            ``LeanExportConfig.project_name``).
        main_cs_path: Absolute path to the generated ``Main.cs``.
        config_json_path: Absolute path to the generated ``config.json``.
        research_ipynb_path: Optional path to a research notebook (not
            generated by default; reserved for a future P3.B+ step).
        readme_path: Absolute path to ``README.md``.
        files_written: All files written by the export (so callers can
            tar them up, compute a content hash, etc.).
        policy_hash: ``ProtocolPolicy.policy_hash`` at export time.
    """

    project_name: str
    main_cs_path: Path
    config_json_path: Path
    readme_path: Path
    files_written: list[Path]
    policy_hash: str
    research_ipynb_path: Optional[Path] = None


