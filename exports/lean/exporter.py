# Map of Aurora strategy class short-name -> translation tier. The
# short-name is the last segment of ``strategy_class`` (e.g.
# "aurora.strategies.library.ma_cross.MACross" -> "MACross"). Tier
# is purely informational; the actual rendered logic is decided by
# :meth:`LeanExporter._render_indicator_decls` etc.
TRANSLATION_TIERS: dict[str, str] = {
    "MACross": "full",
    "RSIMeanRev": "full",
    "TSMomentum": "partial",
    "BollingerMR": "partial",
    "DonchianBreakout": "partial",
    "ATRBreakout": "partial",
    "DualMomentum": "partial",
    "VolTargetWrapper": "partial",
    "StopWrapper": "partial",
    "PairTrade": "scaffold-only",
    "OnlineLearner": "scaffold-only",
    "SeqModelStrategy": "scaffold-only",
    "PairDiscoveryEngine": "scaffold-only",
    "StatArbMeanRev": "scaffold-only",
    "Momentum": "partial",
    "MeanReversion": "partial",
}


def list_translation_tiers() -> list[tuple[str, str]]:
    """Return ``[(class_name, tier), ...]`` sorted by class name.

    Used by ``forge export lean-list`` to show operators which
    strategies have a full Lean translation vs a TODO scaffold.
    """
    return sorted(TRANSLATION_TIERS.items(), key=lambda kv: kv[0])


