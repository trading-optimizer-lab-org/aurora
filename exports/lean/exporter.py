_TEMPLATES_DIR = Path(__file__).resolve().parent / "templates"


def _read_template(name: str) -> Template:
    path = _TEMPLATES_DIR / name
    return Template(path.read_text(encoding="utf-8"))


def _safe_class_name(raw: str) -> str:
    """Sanitize ``raw`` to a valid C# class identifier.

    C# identifiers: letter/_ followed by letters/digits/_. Anything else
    is replaced with ``_``; if the first char is a digit a leading ``_``
    is prepended.
    """
    out = []
    for ch in raw:
        if ch.isalnum() or ch == "_":
            out.append(ch)
        else:
            out.append("_")
    s = "".join(out) or "QFExportedAlgorithm"
    if s[0].isdigit():
        s = "_" + s
    return s


def _short_class_name(strategy_class: str) -> str:
    """Return the last segment of a fully-qualified import path."""
    if "." in strategy_class:
        return strategy_class.rsplit(".", 1)[-1]
    return strategy_class


def _params_block_md(params: dict) -> str:
    """Render params as a fenced JSON block for the README."""
    if not params:
        return "_(no parameters)_"
    body = json.dumps(params, indent=2, sort_keys=True, default=str)
    return "```json\n" + body + "\n```"


def _params_comment(params: dict) -> str:
    """Render params as ``// key: value`` comment lines for Main.cs."""
    if not params:
        return "//   (no parameters)"
    lines = []
    for k in sorted(params.keys()):
        v = params[k]
        lines.append(f"//   {k}: {json.dumps(v, default=str)}")
    return "\n".join(lines)


def _coerce_universe(spec: Any) -> list[str]:
    """Best-effort recovery of a tickers list from a spec.

    Order: ``spec.universe`` -> ``spec.params['universe']`` -> ``[]``.
    """
    u = getattr(spec, "universe", None)
    if isinstance(u, list) and u:
        return [str(x) for x in u]
    p = getattr(spec, "params", None) or {}
    if isinstance(p, dict):
        u2 = p.get("universe")
        if isinstance(u2, list) and u2:
            return [str(x) for x in u2]
    return []


def _coerce_rebalance(spec: Any) -> str:
    return str(getattr(spec, "rebalance", "1d") or "1d")


def _coerce_strategy_class(spec: Any) -> str:
    """Return ``strategy_class`` if present, else fall back to ``name``.

    GA-style specs only carry ``name``; in that case the class name is
    used as both the display name and the translation key.
    """
    sc = getattr(spec, "strategy_class", None)
    if sc:
        return str(sc)
    name = getattr(spec, "name", "") or ""
    return str(name)


def _coerce_spec_hash(spec: Any) -> str:
    """Return ``spec.spec_hash`` if present, else SHA-256 over params.

    The fallback exists so a GA spec (no spec_hash) can still be
    exported with deterministic provenance. The fallback hash is
    computed from a sorted JSON payload of name + params; two GA specs
    with the same name + params therefore hash to the same value.
    """
    sh = getattr(spec, "spec_hash", None)
    if sh:
        return str(sh)
    name = getattr(spec, "name", "") or ""
    params = getattr(spec, "params", {}) or {}
    payload = json.dumps(
        {"name": str(name), "params": dict(params)},
        sort_keys=True, separators=(",", ":"), default=str,
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def _qf_version() -> str:
    try:
        from aurora import __version__ as v
        return str(v)
    except Exception:
        return "0.0.0+local"


def _indent_json(obj: Any, *, indent_spaces: int = 4, base_indent: int = 4) -> str:
    """JSON-encode ``obj`` indented for a nested template position.

    ``json.dumps(..., indent=4)`` always anchors at column 0; when we
    splice the result into the middle of another JSON template we need
    every line *after the first* to start at the column of the
    surrounding key. ``base_indent`` is how many spaces precede the
    surrounding key in the template, so the continuation lines line up
    cleanly.
    """
    raw = json.dumps(obj, indent=indent_spaces, sort_keys=True, default=str)
    if "\n" not in raw:
        return raw
    pad = " " * base_indent
    lines = raw.split("\n")
    return lines[0] + "\n" + "\n".join(pad + ln for ln in lines[1:])


