        meta = json.loads((args.select / "real" / "meta.json").read_text(encoding="utf-8"))
        tp = tail_picks(monthly, counts, meta, D)
        months = monthly.index
        cm = R22._cash_m(D, months)

        def wfm(pk: dict) -> float:
            parts = [monthly[f"{n}|mid"].loc[f"{y}-01-01":f"{y}-12-31"]  # type: ignore[misc]
                     for y, n in sorted(pk.items()) if f"{n}|mid" in monthly]
            if not parts:
                return np.nan
            m = pd.concat(parts)
            m = m[m.index >= pd.Timestamp("2018-01-01")]
            rows_ = np.isin(months, m.index)
            return float(core.sortino_cols(m.reindex(months[rows_]).to_numpy()[:, None], cm[rows_])[0])
        L += ["", "## 3. The tail rule (comparison only; the owner chose selection by Sortino alone)", "",
              "A configuration may be picked for a year only if no trade it took before that year lost more than 100% "
              "of the position.", "", "| family | Sortino 2018+ (monthly) with the rule | without (the report's) |",
              "|---|---|---|"]
        for fam, picks in tp.items():
            mine = summ["families"].get(fam, {}).get("picks", {})
            L.append(f"| {fam} | {_f2(wfm(picks))} | {_f2(wfm({int(y): n for y, n in mine.items()}))} |")
