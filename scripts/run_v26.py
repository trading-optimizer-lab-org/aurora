    L = ["# v26 after the report: own exits, robustness, the tail rule and one account", "",
         "## 1. The shield against each family's own exit (walk-forward 2018+, middle R4 costs)", "",
         "| family | v26 Sortino | v26 CAGR | v26 max DD | own exit Sortino (v26 costs) | own CAGR | own max DD | "
         "source run's Sortino | nights in the night store |", "|---|---|---|---|---|---|---|---|---|"]
    for r in rob:
        b, o = r.get("base") or {}, r.get("own") or {}
        cov = f"{r['nights_covered'] / r['nights_held']:.0%}" if r.get("nights_held") else "-"
