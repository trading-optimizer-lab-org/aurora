def _source_trades(src: str, key: str, g: dict):
    D, ev, E = R14._G["D"], R14._G["store"], R16._W["E"]
    if src == "v19":
        return v19.intraday_trades(ev, D, key, g)
    if src == "v20":
        return v20.intraday_trades(ev, D, key, g)
    if src == "v22":
        return vin.intraday_trades(ev, D, key, g)
    if src == "v23":
        return v23.trades(ev, R14._G["liquid"], D, key, g)
    return v25.trades(R14._G["v25"], D, key, g)


def entries(key: str, name: str) -> tuple[str, dict, list]:
    """(kind, the source configuration, its captured intraday entries or its daily specs), once per worker."""
    if name not in _E:
        global _CAP
        src, fam = key.split(":")
        kind, cfgs = source_registry(src)[fam]
        g = dict(cfgs[int(name.split("|")[1])])
        if kind == "intra":
            g["exit"] = "d3"
            _CAP = []
            try:
                _source_trades(src, fam, g)
                caps = _CAP
            finally:
                _CAP = None
            if any(c[3] > 0 for c in caps):
                raise ValueError(f"{name}: a long entry; the shield is for shorts")
            data = [(cd, b, line, j, e, stop, prio) for cd, b, line, _, j, e, stop, prio in caps]
        else:
            D, E = R14._G["D"], R16._W["E"]
            data = (v19.daily_specs if src == "v19" else v20.daily_specs)(D, E, fam, g)
            if any(s.side > 0 for s in data):
                raise ValueError(f"{name}: a long entry; the shield is for shorts")
        _E[name] = (kind, g, data)
    return _E[name]


def _keep_rows(tr: pd.DataFrame, filt: str) -> pd.DataFrame:
    if filt == "none" or tr.empty:
        return tr
    j = tr["symbol"].astype(str).map(R14._G["cols"])
    ok = j.notna().to_numpy()
    k = np.zeros(len(tr), bool)
    k[ok] = sh.keep(R14._G["D"], tr["t"].to_numpy(int)[ok], j[ok].to_numpy(int), filt)
    return tr[k]


def _keep_specs(specs: list, filt: str) -> list:
    if filt == "none" or not specs:
        return specs
    k = sh.keep(R14._G["D"], np.array([s.t for s in specs]), np.array([s.j for s in specs]), filt)
    return [s for s, ok in zip(specs, k) if ok]


def _placebo_intra(src: str, fam: str, g: dict, real: pd.DataFrame, rng: np.random.Generator) -> pd.DataFrame:
    D, ev = R14._G["D"], R14._G["store"]
    pk = (src, fam, g.get("scope"), g.get("band"))
    if src in ("v19", "v20"):
        if pk not in _P:
            _P[pk] = (v19 if src == "v19" else v20).pool_by_day(ev, fam, g["band"])
        return v19.intraday_placebo(ev, D, real, rng, _P[pk])
    if src == "v22":
        if pk not in _P:
            _P[pk] = vin.pool_by_day(ev, g)
        return vin.intraday_placebo(ev, D, fam, g, real, rng, _P[pk])
    if src == "v23":
        if pk not in _P:
            _P[pk] = v23.pool_by_day(ev, R14._G["liquid"], g)
        st, pool = _P[pk]
        return v23.placebo(st, pool, D, fam, g, real, rng)
    stores = R14._G["v25"]
    pk = (src, g["scope"], g["band"], g.get("sel"))
    if pk not in _P:
        _P[pk] = v24.pool_by_day(stores, g)
    return v25.placebo(stores, _P[pk], D, fam, g, real, rng)


def shield_trades(key: str, cfg: dict) -> tuple[str, dict, object]:
    """(kind, source configuration, the configuration's trades or specs after its name filter) under the shield
    already set with sh.set_params."""
    kind, g, data = entries(key, cfg["entry"])
    if kind == "intra":
        D = R14._G["D"]
        tr = pd.DataFrame([sh.intra_row(D, *a) for a in data], columns=v19.COLS)
        return kind, g, _keep_rows(tr, cfg["filt"])
    return kind, g, _keep_specs(data, cfg["filt"])


def evaluate(key: str, ci: int, placebo_rng: np.random.Generator | None = None) -> tuple:
    cfg = registry()[key][1][ci]
    src, fam = key.split(":")
    D, table = R14._G["D"], R16._W["table"]
    dates = D["dates"]
    sh.set_params({k: cfg[k] for k in ("hold", "stop", "ext", "rally", "scale")})
    v19.set_costs("r4", R22.SLIP, R22.R4)
    try:
        kind, g, x = shield_trades(key, cfg)
        if placebo_rng is not None:
            if kind == "intra":
                pt = _keep_rows(_placebo_intra(src, fam, g, x, placebo_rng), cfg["filt"])
                return v19.intra_book(pt, dates, table, 1.0)[0], None, None
            pl = (v19.daily_placebo if src == "v19" else v20.daily_placebo)(D, x, placebo_rng, g.get("band"))
            return v19.daily_book(D, _keep_specs(pl, cfg["filt"]), table, 1.0)[0], None, None
        out, paths, taken = {}, [], np.zeros(0, bool)
        for name, half, spread, fee, gross in R22.SCEN:
            v19.set_costs("r4", R22.SLIP, half)
            if kind == "intra":
                s, p_, t_ = v19.intra_book(x, dates, table, spread, fee, gross)
            else:
                s, p_, t_ = v19.daily_book(D, x, table, spread, fee, gross)
            out[name] = s
            if name == "mid":
                paths, taken = p_, t_
        v19.set_costs("r4", 0.0, R22.R4)
        _, _, x0 = shield_trades(key, cfg)  # the gross record: no costs and no slippage
        out["gross"] = (v19.intra_book(x0, dates, table, 0.0, 1.0, True) if kind == "intra"
                        else v19.daily_book(D, x0, table, 0.0, 1.0, True))[0]
        return out, paths, taken
    finally:
        sh.set_params(None)
        v19.set_costs("r4", R22.SLIP, R22.R4)


