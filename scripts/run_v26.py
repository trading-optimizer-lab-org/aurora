def coverage(name: str) -> tuple[int, int]:
    """(nights held by the configuration's trades, of them in the night store's downloaded nights)."""
    key, ci = _split(name)
    cfg = registry()[key][1][ci]
    kind, _, data = entries(key, cfg["entry"])
    got = sh.NIGHTS.fetched if sh.NIGHTS is not None else set()
    n = sh.HOLD[cfg["hold"]]
    if kind == "intra":
        rows = [(int(a[0]["t"]), n) for a in data]
    else:
        rows = [(s.t, n + int(s.kind == "close")) for s in data]
    held = [t + k for t, m in rows for k in range(m)]
    return len(held), sum(1 for u in held if u in got)


def _split(name: str) -> tuple[str, int]:
    key, ci = name.rsplit("|", 1)
    return key, int(ci)


def _delayed(a: tuple, d: int) -> tuple | None:
    """An intraday entry d minutes later, at that bar's open, with the same stop distance."""
    cd, b, line, j, e, stop, prio = a
    k = int(np.searchsorted(b[0], b[0][j] + d))
    if k >= len(b[0]):
        return None
    e2 = float(b[1][k])
    return cd, b, line, k, e2, e2 * stop / e, prio


def _ssr_day(D: dict, t: int, j: int, low_before: float, pc: float) -> bool:
    """The short-sale restriction in force at the entry: a fall of 10% from the prior close that day before the
    entry, or on the session before."""
    L, C = D["L"], D["C"]
    prior = t >= 2 and np.isfinite(L[t - 1, j]) and L[t - 1, j] <= 0.9 * C[t - 2, j]
    return bool(prior or (np.isfinite(low_before) and low_before <= 0.9 * pc))


_ROWS: dict = {}


def pick_book(name: str, spread: float = 1.0, fee: float = 1.0, slip: float | None = None, delay: int = 0,
              drop: tuple | None = None, ssr: bool = False) -> tuple:
    """(daily returns at the middle costs unless stated, paths, taken) of one v26 configuration under a change."""
    key, ci = _split(name)
    cfg = registry()[key][1][ci]
    D, table = R14._G["D"], R16._W["table"]
    sh.set_params({k: cfg[k] for k in ("hold", "stop", "ext", "rally", "scale")})
    v19.set_costs("r4", R22.SLIP if slip is None else slip, R22.R4)
    try:
        kind, g, data = entries(key, cfg["entry"])
        if kind == "intra":
            rk = (name, slip, delay, ssr)
            if rk not in _ROWS:
                args = data if delay == 0 else [x for a in data if (x := _delayed(a, delay)) is not None]
                if ssr:
                    args = [a for a in args if not _ssr_day(D, int(a[0]["t"]), int(a[0]["j"]),
                                                            float(np.min(a[1][3][:a[3] + 1])), float(a[0]["pc"]))]
                _ROWS[rk] = _keep_rows(pd.DataFrame([sh.intra_row(D, *a) for a in args], columns=v19.COLS),
                                       cfg["filt"])
            tr = _ROWS[rk]
            if drop is not None:
                tr = tr[drop[0].random(len(tr)) >= drop[1]]
            return v19.intra_book(tr, D["dates"], table, spread, fee)
        specs = _keep_specs(data, cfg["filt"])
        if ssr:
            O, L, C = D["O"], D["L"], D["C"]
            specs = [s for s in specs if not _ssr_day(D, s.t, s.j, float(O[s.t, s.j] if s.kind == "open"
                                                                         else L[s.t, s.j]), float(C[s.t - 1, s.j]))]
        if drop is not None:
            specs = [s for s in specs if drop[0].random() >= drop[1]]
        return v19.daily_book(D, specs, table, spread, fee)
    finally:
        sh.set_params(None)
        v19.set_costs("r4", R22.SLIP, R22.R4)


def without_top(paths: list, taken: np.ndarray, dates: pd.DatetimeIndex, share: float) -> pd.Series:
    """The book rebuilt without the best ``share`` of the trades it took (by net return)."""
    net = np.array([float(np.sum(p[1])) for p in paths])
    idx = np.flatnonzero(taken)
    k = int(np.ceil(share * len(idx)))
    drop = set(idx[np.argsort(-net[idx])[:k]].tolist()) if k else set()
    return v19.book_paths([p for i, p in enumerate(paths) if i not in drop], dates)[0]


def stitch(series: dict, picks: dict, index: pd.DatetimeIndex, end: pd.Timestamp) -> pd.Series:
    """A walk-forward stream: each year, that year's pick."""
    parts = [series[n].loc[pd.Timestamp(f"{y}-01-01"):min(end, pd.Timestamp(f"{y}-12-31"))]
             for y, n in sorted(picks.items())]
    return (pd.concat(parts) if parts else pd.Series(dtype=float)).reindex(index).fillna(0.0)


def own_book(src: str, name: str) -> pd.Series:
    """The source configuration with its own exit (no shield), at v26's middle costs."""
    key, ci = _split(name)
    kind, cfgs = source_registry(src)[key]
    g = cfgs[ci]
    D, table, E = R14._G["D"], R16._W["table"], R16._W["E"]
    v19.set_costs("r4", R22.SLIP, R22.R4)
    if kind == "intra":
        return v19.intra_book(_source_trades(src, key, g), D["dates"], table, 1.0)[0]
    specs = (v19.daily_specs if src == "v19" else v20.daily_specs)(D, E, key, g)
    return v19.daily_book(D, specs, table, 1.0)[0]


