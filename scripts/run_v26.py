def source_registry(src: str) -> dict[str, tuple[str, list[dict]]]:
    """The configurations exactly as the source run numbered them."""
    if src == "v19":
        dims = [("intra", v19.INTRA_DIMS), ("daily", v19.DAILY_DIMS)]
    elif src == "v20":
        dims = [("intra", v20.INTRA_DIMS), ("daily", v20.DAILY_DIMS)]
    elif src == "v22":
        dims = [("daily", ta.DAILY_DIMS), ("intra", vin.INTRA_DIMS)]
    elif src == "v23":
        dims = [("intra", v23.INTRA_DIMS)]
    else:
        dims = [("intra", v25.INTRA_DIMS)]
    return {k: (kind, core.grid(d)) for kind, dd in dims for k, d in dd.items()}


def entries_of() -> dict[str, tuple[str, list[str]]]:
    """'src:KEY' -> (kind, the distinct walk-forward picks of the family), for the families that passed their gate."""
    out = {}
    for src, fams in FAMILIES.items():
        summ = json.loads((DATA / SUMMARIES[src]).read_text(encoding="utf-8"))["families"]
        reg = source_registry(src)
        for fam in fams:
            picks = sorted(set(summ[fam]["picks"].values()))
            key = picks[0].split("|")[0]
            out[f"{src}:{key}"] = (reg[key][0], picks)
    return out


def shield_grid(kind: str, picks: list[str]) -> list[dict]:
    """The shield crossed with the entries; an intraday entry held to its own close has no night, so no extended-
    session rule and no split cover."""
    out = []
    for entry in picks:
        for hold in sh.HOLD:
            for stop in sh.STOPS:
                for filt in sh.FILTERS:
                    if kind == "intra" and hold == "d1":
                        out.append({"entry": entry, "hold": hold, "stop": stop, "ext": "none", "rally": "none",
                                    "scale": "all", "filt": filt})
                        continue
                    for ext in sh.EXT:
                        for rally in sh.RALLY:
                            for scale in sh.SCALE:
                                out.append({"entry": entry, "hold": hold, "stop": stop, "ext": ext, "rally": rally,
                                            "scale": scale, "filt": filt})
    return out


def registry() -> dict[str, tuple[str, list[dict]]]:
    if "reg" not in _S:
        _S["reg"] = {k: (kind, shield_grid(kind, picks)) for k, (kind, picks) in entries_of().items()}
    return _S["reg"]


def configs() -> list[tuple[str, int]]:
    return [(k, i) for k, (_, cfgs) in registry().items() for i in range(len(cfgs))]


def _store(folder: Path) -> vi.Store:
    arr = np.load(folder / "store.npz")
    return vi.Store(pd.read_parquet(folder / "cands.parquet"), {k: arr[k] for k in vi.FIELDS})


def ext_halves(spreads: pd.DataFrame | None, base: np.ndarray) -> np.ndarray:
    """R4 with two more legs, the after-hours and the premarket: half the median quoted spread of each price tier
    measured in those sessions; twice the session's half-spread where fewer than 50 quotes were found."""
    out = np.hstack([base, 2 * base[:, 1:2], 2 * base[:, 1:2]])
    if spreads is None or spreads.empty:
        return out
    q = spreads.dropna(subset=["spread"])
    for (session, tier), grp in q.groupby(["session", "tier"]):
        if len(grp) >= MIN_QUOTES and 0 <= int(tier) < len(base):
            out[int(tier), sh.LEG_AH + int(session)] = float(grp["spread"].median()) / 2
    return out


def load(base: Path) -> None:
    _base_load(base)
    D, ev = R14._G["D"], R14._G["store"]
    lq, mv = _store(LIQUID), _store(MOVERS)
    R14._G["liquid"] = lq
    st25 = {"event": vi.Store(ev.cands.copy(), ev.arrays), "liquid": vi.Store(lq.cands.copy(), lq.arrays),
            "mover": mv}
    v25.prepare(st25, D)
    R14._G["v25"] = st25
    sh.prepare(D)
    if not os.environ.get("V26_NO_NIGHTS"):  # the early canary runs before the night store exists
        sh.NIGHTS = sh.Nights(pd.read_parquet(NIGHT / "nights.parquet"), dict(np.load(NIGHT / "nights.npz")))
    sp = pd.read_parquet(NIGHT / "spreads.parquet") if (NIGHT / "spreads.parquet").exists() else None
    r4x = ext_halves(sp, R22.R4)
    auction = r4x.copy()
    auction[:, 0], auction[:, 2] = r4x[:, 1], r4x[:, 1]
    R22.R4 = r4x
    R22.SCEN = (("mid", r4x, 1.0, 1.0, False), ("low", r4x, 0.5, 1.0, False), ("high", r4x, 2.0, 3.0, False),
                ("auction", auction, 1.0, 1.0, False))
    R14._G["cols"] = {str(s): i for i, s in enumerate(D["cols"])}


# ---------------------------------------------------------------- the patches

_ORIG_ROW, _ORIG_PATH = v19.trade_row, v19.path19
_CAP: list | None = None
_DUMMY = {c: 0 for c in v19.COLS}


def _row(D, cd, b, line, side, j, e, stop, rule, prio, close_level=np.nan):
    if _CAP is not None:
        _CAP.append((cd, b, line, side, j, e, stop, prio))
        return _DUMMY
    if sh.PARAMS is not None and side < 0:
        return sh.intra_row(D, cd, b, line, j, e, stop, prio)
    return _ORIG_ROW(D, cd, b, line, side, j, e, stop, rule, prio, close_level)


def _path(D, s, table, spread, fee_mult=1.0, gross=False, w_max=0.05):
    if sh.PARAMS is not None and s.side < 0:
        return sh.daily_path(D, s, table, spread, fee_mult, gross, w_max)
    return _ORIG_PATH(D, s, table, spread, fee_mult, gross, w_max)


v19.trade_row = _row
v19.path19 = _path


