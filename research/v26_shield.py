"""v26: the squeeze shield for the small-cap shorts. Pre-registered in docs/research/V26_PREREGISTRATION.md.

Every family that passed its gate in v19r, v20, v22c, v23b and v25 keeps its own entry (its walk-forward picks,
generated by its own code) and gets a new exit: a holding period, a stop, a stop that is also live in the after-hours
session and the next premarket, an exit when the price rallies in those sessions, and a split cover. A short is held
on the daily bars between sessions as in v19 (the stop at the daily high, filled at the open when the open is beyond
it) and on the night store's minute bars between 16:00 and the next 09:29. Prices are on the split-adjusted scale
while a trade is walked; returns are on the entry price.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from aurora.research import v14_core as core
from aurora.research import v19_grid as v19

HOLD = {"d1": 0, "d2": 1, "d3": 2, "d5": 4}  # closes after the first close (an entry at a close: after the entry)
STOPS = ("own", "pct10", "pct20", "pct35", "pct50", "atr2", "atr4")
EXT = ("none", "ah", "pm", "both")
RALLY = ("none", "r5", "r15")  # out in the extended sessions at a rise of 5% / 15% over the last close
SCALE = ("all", "half", "third")
FILTERS = ("none", "so10", "so20", "offer90", "nosq60")
AH_END = 240  # night minutes 0-239: 16:00-19:59 of the session; 240-569: 04:00-09:29 of the next one
LEG_AH, LEG_PM = 3, 4  # cost legs after v19's open (0), session (1) and close (2)
OFFER_ROWS, SQUEEZE_ROWS, SQUEEZE = 63, 60, 1.0

PARAMS: dict | None = None  # the shield of the configuration being evaluated (None: the families' own exits)
EXIT: dict = {}  # where the last trade walked left: session row, kind (session/open/stop/close/ah/pm), minute
NIGHTS: "Nights | None" = None
FACTS: dict = {}


class Nights:
    """The v26 night store: one row a (night, column), minutes after 16:00 of the night's session."""

    def __init__(self, index: pd.DataFrame, arrays: dict) -> None:
        self.pos = dict(zip(zip(index["u"].to_numpy(int), index["j"].to_numpy(int)),
                            zip(index["off"].to_numpy(int), index["n"].to_numpy(int))))
        self.a = {k: arrays[k] for k in ("m", "o", "h", "l", "c")}
        self.fetched = set(np.asarray(arrays["fetched"], int).tolist())

    def bars(self, u: int, j: int) -> tuple | None:
        """(m, o, h, l, c) of column j over night u; None when that night was not downloaded."""
        if u not in self.fetched:
            return None
        off, n = self.pos.get((u, j), (0, 0))
        return tuple(self.a[k][off:off + n] for k in ("m", "o", "h", "l", "c"))


def set_params(p: dict | None) -> None:
    global PARAMS
    PARAMS = p


def prepare(D: dict) -> None:
    """The facts the stops and filters read, all from the sessions before the entry: the 14-day average true range
    (split-adjusted), an offering filing in the 63 sessions up to the entry session, a +100% day in the 60 sessions
    before the session before the entry."""
    H, L, C = (np.asarray(D[k], float) for k in ("H", "L", "C"))
    prev = np.vstack([np.full((1, C.shape[1]), np.nan), C[:-1]])
    tr = np.fmax(H - L, np.fmax(np.abs(H - prev), np.abs(L - prev)))
    atr = pd.DataFrame(tr).rolling(14, min_periods=14).mean().shift(1).to_numpy(np.float32)
    off = np.zeros(C.shape, np.float32)
    tab = D["events"]["offering"]
    off[tab["t"].to_numpy(int).clip(0, C.shape[0] - 1), tab["j"].to_numpy(int)] = 1.0
    offer = pd.DataFrame(off).rolling(OFFER_ROWS, min_periods=1).max().to_numpy() > 0
    with np.errstate(invalid="ignore", divide="ignore"):
        r1 = C / prev - 1
    sq = pd.DataFrame(np.nan_to_num(r1, nan=0.0)).rolling(SQUEEZE_ROWS - 1, min_periods=1).max().shift(2)
    FACTS.update({"atr": atr, "offer": offer, "squeeze": sq.to_numpy() >= SQUEEZE})


def keep(D: dict, t: np.ndarray, j: np.ndarray, rule: str) -> np.ndarray:
    """The trades a name filter keeps (shares outstanding known and at least 10 or 20 million; an offering filing in
    the 63 sessions up to the entry; no +100% day in the 60 sessions before the setup day)."""
    t, j = np.asarray(t, int), np.asarray(j, int)
    if rule == "none" or len(t) == 0:
        return np.ones(len(t), bool)
    if rule in ("so10", "so20"):
        so = np.asarray(D["SO"], float)[t, j]
        return np.isfinite(so) & (so >= (10e6 if rule == "so10" else 20e6))
    if rule == "offer90":
        return FACTS["offer"][t, j]
    return ~FACTS["squeeze"][t, j]


def stop_level(rule: str, e: float, own: float, t: int, j: int, scale: float) -> float:
    """A short's stop on the price scale of ``e`` (``scale``: that scale over the split-adjusted one). Without an ATR
    (fewer than 14 sessions) the ATR stops fall back to 20%."""
    if rule == "own":
        return own
    if rule.startswith("pct"):
        return e * (1 + int(rule[3:]) / 100)
    a = float(FACTS["atr"][t, j]) * scale
    return e + int(rule[3:]) * a if np.isfinite(a) and a > 0 else e * 1.20


def fractions(rule: str, closes: int) -> list[float]:
    """The part of the position covered at each close (the last close covers the rest)."""
    f = [0.0] * closes
    if closes <= 1 or rule == "all":
        return f
    if rule == "half":
        f[0] = 0.5
    else:
        f[0] = 1 / 3
        if closes >= 3:
            f[1] = 1 / 3
    return f


def _night(u: int, j: int, stop: float, prev: float, F: np.ndarray, P: dict) -> tuple[float, int, int] | None:
    """(fill, leg, night minute) of an exit in the after-hours of session u or the premarket of u + 1, else None."""
    if NIGHTS is None or (P["ext"] == "none" and P["rally"] == "none"):
        return None
    b = NIGHTS.bars(u, j)
    if b is None or len(b[0]) == 0:
        return None
    m, o, h, c = b[0], b[1], b[2], b[4]
    f_ah, f_pm = float(F[u, j]), float(F[u + 1, j]) if u + 1 < F.shape[0] else np.nan
    for k in range(len(m)):
        pm = m[k] >= AH_END
        f = f_pm if pm else f_ah
        if not np.isfinite(f) or f <= 0:
            continue
        ok, hh, cc = float(o[k]) * f, float(h[k]) * f, float(c[k]) * f
        live = P["ext"] == "both" or P["ext"] == ("pm" if pm else "ah")
        if live and hh >= stop:
            return (ok if ok >= stop else v19._slip(stop, hh)), (LEG_PM if pm else LEG_AH), int(m[k])
        if P["rally"] != "none" and cc >= prev * (1 + int(P["rally"][1:]) / 100):
            return cc, (LEG_PM if pm else LEG_AH), int(m[k])
    return None


def walk(D: dict, u0: int, j: int, e: float, stop: float, prev: float, w: float, fracs: list[float],
         P: dict) -> tuple[list[float], float, int]:
    """A short open after the close of session u0 (all on the split-adjusted scale): its returns on the sessions
    after u0, the nights it was held (weighted by the part still open) and its exit leg. ``fracs`` covers a part at
    each close walked; the last close covers the rest."""
    O, H, C, F, new = D["O"], D["H"], D["C"], D["F"], D["new"]
    T = C.shape[0]
    rets, nights, leg = [], 0.0, 2
    for k, fr in enumerate(fracs):
        u = u0 + k + 1
        if u >= T:
            break
        hit = _night(u - 1, j, stop, prev, F, P)
        if hit is not None:
            px, leg, mm = hit
            nights += w if leg == LEG_PM else 0.0
            rets.append(w * (prev - px) / e)
            EXIT.update(row=u - 1 if leg == LEG_AH else u, kind="ah" if leg == LEG_AH else "pm", minute=mm)
            return rets, nights, leg
        c = float(C[u, j])
        if new[u, j] or not np.isfinite(c):
            leg = 2
            EXIT.update(row=u - 1, kind="close", minute=-1)
            break
        o, h = float(O[u, j]), float(H[u, j])
        o = o if np.isfinite(o) else c
        nights += w
        if h >= stop:  # charged the close leg, as v19 charges a carried trade's exit
            px = o if o >= stop else v19._slip(stop, h)
            rets.append(w * (prev - px) / e)
            EXIT.update(row=u, kind="open" if o >= stop else "stop", minute=-1)
            return rets, nights, 2
        tg = P.get("target", "none")  # v28: cover at a fall of 20/30/50% from the entry; v26 has none
        if tg != "none":
            lvl, lo = e * (1 - int(tg[1:]) / 100), float(D["L"][u, j])
            if np.isfinite(lo) and lo <= lvl:
                px = o if o <= lvl else lvl
                rets.append(w * (prev - px) / e)
                EXIT.update(row=u, kind="target", minute=-1)
                return rets, nights, 2
        rets.append(w * (prev - c) / e)
        prev = c
        EXIT.update(row=u, kind="close", minute=-1)
        if k == len(fracs) - 1:
            return rets, nights, 2
        w -= fr
    return rets, nights, leg


def intra_row(D: dict, cd, b: tuple, line: np.ndarray, j: int, e: float, own: float, prio: float) -> dict:
    """v19.trade_row for a short under the shield: the same entry, the shield's stop and exits."""
    P = PARAMS
    assert P is not None
    t, col = int(cd["t"]), int(cd["j"])
    f = float(D["F"][t, col])
    stop = stop_level(P["stop"], e, own, t, col, 1.0 / f if np.isfinite(f) and f > 0 else np.nan)
    if not np.isfinite(stop) or stop <= e:
        stop = e * 1.20
    px, held, k = v19.exit_bar(-1, j, e, stop, "d3", b, line, float(cd["pc"]))
    rets, nights = [(e - px) / e], 0.0
    leg = 2 if held or k == len(b[4]) - 1 else 1
    EXIT.clear()
    EXIT.update(row=t, kind="close" if leg == 2 else "session", minute=int(b[0][k]))
    closes = HOLD[P["hold"]]
    if held and closes > 0 and np.isfinite(f) and f > 0:
        fr = fractions(P["scale"], closes + 1)
        w = 1.0 - fr[0]
        more, nights, leg = walk(D, t, col, e * f, stop * f, px * f, w, fr[1:], P)
        rets += more
    m, c, v, vw = b[0], b[4], b[5], b[6]
    pv = np.where(np.isfinite(vw) & (vw > 0), vw, c)
    leg_in = 0 if (j == 0 and e == float(b[1][0])) else 1
    return {"date": cd["date"], "t": t, "symbol": cd["symbol"], "minute": int(m[j]), "side": -1, "entry": e,
            "stop": stop, "price": float(cd["open"]), "liq": float(cd["pmv"]) + float(np.sum(pv[:j] * v[:j])),
            "prio": prio, "so": float(cd.get("so", np.nan)), "rets": np.array(rets), "nights": nights, "rule": "d3",
            "opens": int(leg_in == 0) + int(leg == 0), "xmin": -1 if held else int(m[k]), "leg_in": leg_in,
            "leg_out": leg, "x_row": EXIT.get("row", t), "x_kind": EXIT.get("kind", "close"),
            "x_min": EXIT.get("minute", -1)}


def daily_path(D: dict, s: v19.Spec, table: dict, spread: float, fee_mult: float, gross: bool,
               w_max: float) -> tuple[int, np.ndarray, float, float] | None:
    """v19.path19 for a short under the shield."""
    P = PARAMS
    assert P is not None
    O, H, C, P_raw = D["O"], D["H"], D["C"], D["P"]
    T = C.shape[0]
    t, j = s.t, s.j
    own = s.stop
    closes = HOLD[P["hold"]]
    if s.kind == "close":
        e, first, raw = float(C[t, j]), t + 1, float(P_raw[t, j])
    else:
        e, first = float(O[t, j]), t
        raw = float(P_raw[t - 1, j] * (e / C[t - 1, j])) if t > 0 and C[t - 1, j] > 0 else float(P_raw[t, j])
    if not np.isfinite(e) or e <= 0 or first >= T or not np.isfinite(raw):
        return None
    own_lvl = e * (1 + own) if np.isfinite(own) else np.inf
    stop = stop_level(P["stop"], e, own_lvl, t, j, 1.0)
    if not np.isfinite(stop) or stop <= e:
        stop = np.inf if P["stop"] == "own" else e * 1.20
    EXIT.clear()
    if s.kind == "close":
        rets, nights, leg = walk(D, t, j, e, stop, e, 1.0, fractions(P["scale"], closes + 1), P)
        leg_in = 2
    else:
        h, c = float(H[t, j]), float(C[t, j])
        if not np.isfinite(c):
            return None
        leg_in = 0
        if h >= stop:
            rets, nights, leg = [(e - v19._slip(stop, h)) / e], 0.0, 2
            EXIT.update(row=t, kind="stop", minute=-1)
        else:
            rets, nights, leg = [(e - c) / e], 0.0, 2
            EXIT.update(row=t, kind="close", minute=-1)
            if closes > 0:
                fr = fractions(P["scale"], closes + 1)
                more, nights, leg = walk(D, t, j, e, stop, c, 1.0 - fr[0], fr[1:], P)
                rets += more
    if not rets:
        return None
    r = np.array(rets)
    w = min(w_max, 0.01 * D["DV1"][t, j] / core.ACCOUNT) if np.isfinite(D["DV1"][t, j]) else 0.0
    cost, avail = v19._costs(np.array([raw]), np.array([D["SO"][t, j]]), np.array([-1]), np.array([nights]),
                             np.array([int(leg_in == 0) + int(leg == 0)]), table, spread, fee_mult, gross,
                             (np.array([leg_in]), np.array([leg])))
    if not gross and s.kind == "open" and t > 0 and e <= 0.9 * C[t - 1, j]:
        cost = cost + v19.vs.SSR_EXTRA
    r[0] -= cost[0]
    return first, r, s.prio, w * float(avail[0])
